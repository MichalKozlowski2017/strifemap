export function guessIsoFromText(...parts: (string | null | undefined)[]): string | null {
  const text = parts.filter(Boolean).join(" ");
  if (!text.trim()) return null;
  for (const { re, iso } of PLACE_NAME_ISO) {
    if (re.test(text)) return iso;
  }
  return null;
}

export function countryDisplayName(
  iso: string,
  locale: "pl" | "en",
  fallbackEn?: string | null,
): string {
  const code = iso.toUpperCase();
  if (locale === "pl" && COUNTRY_NAMES_PL[code]) return COUNTRY_NAMES_PL[code];
  return fallbackEn?.trim() || COUNTRY_NAMES_PL[code] || code;
}
